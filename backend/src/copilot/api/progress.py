"""详解档等待期间给用户看的**进度**。

⭐⭐ **这个文件的全部意义是：这里的每一个字都是写死的常量。**

在它之前，直路把模型的 `reasoning_content`（推理模型的原始思维链）
**逐字转发给浏览器**（`providers/llm.py::stream_parts` → `routes/chat.py`
的 `reasoning-delta`）。理由是真的：详解档走的 kimi-k2.6 第一个正文字要
8~60 秒，不发点什么，用户看到的就是「选了详解，它不回答」。

但**用它来填这段空白是拿错东西了**。那段草稿是模型在**完整上下文**里自言自语，
而完整上下文包含：

    system prompt（八条铁律、常识兜底的边界、事实表）
    本轮检索到的材料原文——**含用户自己私有文档的正文**
    材料里可能夹带的提示注入内容
    模型自己推翻掉的中间结论（「也许是设置-快递管理？」）

也就是说：一段被三道闸门拦在答案之外的东西，从**旁边这条管子**原样流了出去。
`INJECTION_GUARD_ENABLED` 把注入成功率压到 0.0%，量的是**正文**；
草稿那一路它一个字都管不到。

⚠️ **这不是"泄露了内部实现"这种程度的问题**，它是隔离红线的一个旁路：
A 的私有文档正文经检索进入上下文后，会出现在发给 A 的草稿里——这一层还好；
但同一条管子也把公共材料原文、system prompt 和注入载荷一起送了出去，
而这三样都是明确不该出现在用户面前的（见 ARCHITECTURE 第四节）。

所以改成：**由系统自己按真实阶段产出进度**。判据只有一条——

    ⚠️⚠️ 这里的字符串必须全部是常量，不许拼接任何来自
    模型、材料、用户输入或数据库的内容。唯一允许的变量是**计数**
    （召回了几条），因为一个整数不构成内容。

`tests/test_progress_events.py` 钉着这条：它把一轮真实的流跑完，
断言发出去的每一个 reasoning 片段都能在这个文件的常量表里找到。

---

**为什么仍然用 `reasoning` 这个 part 类型**（而不是新造一个 `data-progress`）：

1. 前端 `useChat` 已经把它收成独立的 part，和正文天然分开，
   `ReasoningPanel` 也已经有「出正文就自动收起」的行为——那正是进度该有的样子。
2. 换 part 类型要同时改协议、前端类型、历史消息还原三处，
   而这一轮要修的是**内容**不是**通道**。协议不动，回滚的代价就只有一个文件。

⚠️ 进度**不落库**。`_AnswerWriter` 只写正文，这些字从来不进 `messages`——
翻历史时不该看到「正在检索知识库」，那是当时的过程，不是答案的一部分。
"""

from __future__ import annotations

from typing import Final

# 收到提问、还没开始检索。
UNDERSTANDING: Final = "正在理解问题…"
# 正在跑检索 + 重排。
RETRIEVING: Final = "正在检索知识库…"
# 检索完了，`{n}` 是**条数**——唯一允许的变量，一个整数不构成内容。
FOUND: Final = "已找到 {n} 条相关资料"
# 检索完了，一条都没过阈值。
FOUND_NOTHING: Final = "知识库里没有直接匹配的内容"
# 命中人工写定的标准答案，这一轮一次模型调用都不花。
VERIFIED: Final = "已匹配到人工确认过的标准答案"
# 材料备好，开始等模型写正文。**这一句要停留最久**（详解档 8~60 秒）。
GENERATING: Final = "正在整理答案…"

# 全部可能发出去的原文。测试拿它做白名单——
# ⚠️ 新增一句进度就要往这里加一行，否则那道测试立刻变红。
# 这是刻意的：**它要拦的正是"顺手拼一句带上下文的进度"**。
ALL: Final[tuple[str, ...]] = (
    UNDERSTANDING,
    RETRIEVING,
    FOUND,
    FOUND_NOTHING,
    VERIFIED,
    GENERATING,
)


def found(n: int) -> str:
    """「已找到 N 条相关资料」。0 条时换成另一句，别说「已找到 0 条」。"""
    return FOUND.format(n=n) if n > 0 else FOUND_NOTHING
