"""越过工具直答的检测。M10 的**硬**防线——instructions 里那条是软的。

⭐ 这个文件的存在理由，是一次线上路径的实测失败：

    用户：退货入库怎么操作        → 调 answer_kb，答对，5 条引用
    用户：那不良品呢              → **一个工具都没调**，直接给出一段
                                    「方式1：勾选残次品入库…[4]」

那段话读起来和查来的一模一样，还带着 `[4]` 这样的引用标记，但页面上
**0 条引用可点**——因为 `deps.citations` 是空的。而那些编号指向的是
**上一轮**的来源，含义完全错位。

它是怎么来的：`message_history` 里带着上一轮那段 666 字的答案。模型看着
它就够"答"了，于是跳过检索。离线路由评测没抓到，是因为那份题集里的
history 是短的合成字符串，喂不出这个行为。

**所以边界不能只写在 prompt 里。** 模型觉得"这题我会"的时候正是最容易越线的时候，
而越线的样子恰好是一段像模像样、却无据可查的 ERP 操作步骤。
"""

from __future__ import annotations

import re

# ERP 答案的特征：引用标记、界面路径、菜单层级、操作动词。
# 一段**没查知识库**却长成这样的回答，只可能是编的或者是从上一轮抄的。
_CITE = re.compile(r"\[\d{1,2}\]")
_IMG = re.compile(r"\[图\d+\]")
_ERP_MARKS = ("【", "设置–", "设置-", "点击", "勾选", "菜单", "字段", "输入框", "界面")

# 短句不算。调用方只在「这一轮一个工具都没调」时才问到这里，而那种情况下
# Agent 说的只可能是追问（「要对接哪些平台？」）或闲聊，都很短、也不带这些特征
_MIN_LEN = 40


def looks_like_kb_answer(text: str) -> bool:
    """这段话是不是「一段本该来自知识库的答案」。

    判据按可靠性排序：
      1. 带 `[n]` 或 `[图n]` 标记——那是检索材料才有的东西，模型自己写不出
         有效的编号，出现即错位
      2. 够长 **且** 含界面路径/操作动词特征

    ⚠️ **宁可漏判，不可误伤。** 误伤的代价是把一句正常的追问替换成
    「知识库暂无此内容」，那会让多轮收集需求直接卡死；漏判的代价是
    偶尔放过一段无据的答案——后者还有 instructions 那道软防线兜着。

    ⚠️ **调用方必须先确认「这一轮一个工具都没调」。** 只看正文长相是不够的：
    `generate_plan` 之后 Agent 会写一段带界面路径的方案摘要
    （「[必做] 设置–基本设置–店铺 → 创建 5 个店铺」），那段长得和越线的
    一模一样，但它有据——据在刚跑完的那个工具里。
    """
    body = text.strip()
    if not body:
        return False
    if _CITE.search(body) or _IMG.search(body):
        return True
    return len(body) >= _MIN_LEN and any(m in body for m in _ERP_MARKS)
