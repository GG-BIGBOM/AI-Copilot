"""这一问长什么样：**自然语言问句**，还是**直接粘进来的一个串**。

⭐⭐ **它存在的理由是一次被付费评测推翻的默认值。**

W1.2 上线混合检索时默认打开，依据是 45 题关键词题集的免费 `--check`：

    完整问句 30 题   dense 29/30  →  hybrid 29/30    一道题的名次都没变
    裸粘贴   15 条   dense  6/15  →  hybrid 15/15    MRR@5 0.367 → 0.933

2026-08-29 的付费轮把它打了回来（`HYBRID_ENABLED=false`，见 ADR-16 和
`config.hybrid_enabled` 上面那段）：

    公共库·直路 幻觉率   0.0%  →  10.0%
    风险边界 高风险幻觉   0.0%  →  10.0%
    检索命中率          98.5%  →  98.5%   ← 一点没动

机理是同一个动作的两面：纯向量池 top-5 的第 5 位常常是个**重复块**
（等于一个空位），而那个空位正是模型愿意拒答的原因；词法把它填上一块
"话题相邻但不是这件事"的材料，就足以把模型劝离拒答。

⭐ **而两次回退都发生在"完整问句"上**，收益则全部在"裸粘贴"上——
30 题一分没加、15 条从 6 涨到 15。所以按查询形状分流，理论上能保住
100% 的收益、去掉整个伤害面。这个文件就是那个"形状"的判据。

---

## 判据是从题集里量出来的，不是凭感觉写的

把 `eval/keyword.yaml` 45 条按 id 分成两类，逐条看形状（脚本产出）：

    裸粘贴 15 条    问号 0/15    疑问词 0/15    含中文 1/15
    完整问句 30 条  问号 30/30   疑问词 29/30   含中文 30/30

    长度**分不开**：裸粘贴最长 32 字，完整问句最短 18 字

⚠️ **所以不能用长度当判据**，虽然它是最先想到的那个。真正把两类分开的是
「有没有在提问」——而那件事在中文里有一个近乎无例外的标记：句末的问号。

于是判据两步，缺一不可：

    1. 像在提问（有 `？`/`?`，或者有疑问词）  → 一律 dense，**不走词法**
    2. 否则，含不含"标识符形状"的东西        → 含才走词法

第 2 步不能省。少了它，「退货入库流程」这种没带问号的普通短语也会被送去
词法召回——而它恰恰是最容易被"话题相邻"的块带偏的那一类，
也就是上面那 10% 幻觉的成因。

⚠️⚠️ **这里一个模型调用都不花。** 用 LLM 判查询意图是很自然的想法，但它
要在**每一轮检索之前**同步跑一次：多一次网络往返、多一份延迟、多一处
会挂的东西，换来的是一件规则就能判准的事（题集上 45/45）。
这条判据错了最坏也只是这一轮少了或多了词法召回一路——而候选池不放宽任何
东西（见 `retrieve._search`），所以它**不可能**把一个低于阈值的块放进答案。

⚠️ 判据只看**问题本身**，不看语料、不看用户、不看历史。可测、可复现，
`tests/test_selective_hybrid.py` 直接拿 `eval/keyword.yaml` 当输入跑它。
"""

from __future__ import annotations

import re

# 句末问号。中英文都要——用户从别处粘一段英文报错时可能带着半角问号
_QUESTION_MARK = re.compile(r"[?？]")

# 中文疑问词。**故意只收几乎只会出现在提问里的词**，同
# `session_facts._FIELD_ALIASES` 上面那段的取舍：漏判的代价是这一问
# 多走一路词法召回（无害，候选池不放宽任何东西），
# 误判的代价是一道该走词法的裸粘贴退回纯向量（收益丢一半）。
#
# ⚠️ 「哪」单独收，不要写成「哪个|哪些|哪家」那样的枚举：
# 题集里有一条是「建议改用哪两个编码？」，枚举会漏掉它。
# 那一条靠问号也能救，但判据不该依赖两条规则碰巧都命中。
_INTERROGATIVE = re.compile(
    r"怎么|怎样|如何|为什么|为何|什么|哪|多少|几个|多久|是不是|能不能|可不可以|要不要|吗$"
)

# 中日韩统一表意文字。有没有中文是"这是不是从别处粘来的一段外文串"的强信号
_CJK = re.compile(r"[一-鿿]")

# ---- 标识符的三种形状。任一命中即可 ----
#
# ⚠️ 三条都要，一条都不能省——`eval/keyword.yaml` 那 15 条各自命中不同的规则：
#
#     JTSD / YUNDA / POSTB / JOSPIN / QTCK / CD01   连续大写
#     23381383 / 1280269 / [1009]                    长数字
#     entryOrderCode / ownerCode / oldCpCode / mailNo 驼峰
#     gate invalid packet / sid not found            ← 三条都不命中！
#
# 最后那两条只能靠"整句没有一个中文字"来收，见 `is_identifier_query`。

# 连续两个及以上大写字母（`JTSD`、`CD01`、`QTCK`）。
# 要求前后不是小写字母，免得把驼峰词的中段（`entryOrderCode` 里的 `OC`）算进来——
# 那一类由下面的驼峰规则负责，两条规则各管各的更好排查
_UPPER_RUN = re.compile(r"(?<![a-z])[A-Z]{2,}[0-9]*")
# 连续四位及以上数字。三位太短——「3 个仓」「第 100 页」都会命中
_LONG_DIGITS = re.compile(r"\d{4,}")
# 驼峰：小写开头、中间至少一个大写（`ownerCode`、`mailNo`）
_CAMEL = re.compile(r"[a-z]+[A-Z][A-Za-z0-9]*")


def looks_like_question(query: str) -> bool:
    """这一问像不像"在提问"。

    只看两样：句末问号、疑问词。**这是 45 题上唯一无例外把两类分开的信号**
    （问号 30/30 对 0/15）。
    """
    q = (query or "").strip()
    if not q:
        return False
    return bool(_QUESTION_MARK.search(q) or _INTERROGATIVE.search(q))


def has_identifier(query: str) -> bool:
    """含不含"标识符形状"的东西：连续大写 / 长数字 / 驼峰。

    ⚠️ 不包括「整句没有中文」那一条——那是 `is_identifier_query` 的事。
    分开是因为这一个函数回答的是"里面有没有一个像编码的词"，
    而那一条回答的是"这整句是不是从别处粘来的"，两件事。
    """
    q = query or ""
    return bool(_UPPER_RUN.search(q) or _LONG_DIGITS.search(q) or _CAMEL.search(q))


def is_identifier_query(query: str) -> bool:
    """这一问该不该走词法那一路（BM25 + RRF）。

    ⭐ **顺序不能反：先判"像不像提问"，像就直接 False。**
    完整问句里几乎必然也含编码（「平台物流编码 YUNDA 对应哪家快递公司？」
    同时命中问号和大写串）——先判标识符的话，30 道完整问句会被
    全部送去词法召回，而那正是 2026-08-29 被打回来的那个配置。

    第二步两条路，任一即可：

        含标识符形状        `JTSD` / `23381383` / `ownerCode` / `CD01#…`
        整句一个中文都没有  `gate invalid packet` / `sid not found`

    第二条专门收"一整段英文报错原样粘进来"的情形——它没有大写串、
    没有长数字、也没有驼峰，前一条一个都抓不到，而它恰恰是这类查询里
    最典型的一种。在一个中文 ERP 知识库里，一句不含中文、也不在提问的话，
    只可能是从别处复制来的串。
    """
    q = (query or "").strip()
    if not q:
        return False
    if looks_like_question(q):
        return False
    return has_identifier(q) or not _CJK.search(q)
