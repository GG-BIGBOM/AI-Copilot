# 所以 grounded 判定抓不到它——这类错误比编造更难发现。
#
# 试法：在铁律里加第 6 条「问题限定了主体时，材料必须真的是讲这个主体的」。
#
# 结果：**没修好。** 加了之后模型确实多说了一句「材料未说明该配置在星辰电商
# 是否启用」，但开头那句「星辰电商的退货入库流程如下」原样保留，
# 私有库 no_answer 那题仍然不过（幻觉率 100% → 100%）。
#
# 判断：这条新规则和铁律 3「有一部分就答一部分」直接打架，
# 而铁律 3 是 M8 花了整整一轮才调对的（假阴性率 6.1% → 0）。
# 想真修这个，多半不是加一条规则能解决的，得动检索侧
# （让主体名参与过滤/加权），或者在 prompt 里把「主体」提到和「铁律 3」
# 同一层级去重排优先级——两条都要重新过一遍公共库那 55 题。
